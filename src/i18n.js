const zh = { ...zhBase, ...zhApp }
const en = { ...enBase, ...enApp }

const systemLang = () => ((typeof navigator === 'undefined' || /^zh/i.test(navigator.language || '')) ? 'zh' : 'en')

/** The language in use: 'zh' or 'en'. */
export let lang = systemLang()
let dict = lang === 'zh' ? zh : en

/** Switch the UI language: 'system', 'zh' or 'en'. Screens re-render through App. */
export function setLanguage(pref) {
  lang = pref === 'zh' || pref === 'en' ? pref : systemLang()
  dict = lang === 'zh' ? zh : en
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
}

/** Look up a UI string. */
export function t(key) {
  return dict[key] ?? en[key] ?? key
}

/** Fill {name} placeholders. */
export function fill(template, values) {
  return template.replace(/\{(\w+)\}/g, (m, k) => (values[k] !== undefined ? String(values[k]) : m))
}
